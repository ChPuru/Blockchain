#!/usr/bin/env bash
# Rehearse the PoW -> BFT hard fork on a running devnet.
#
# The whole fork is one dispatcher choosing a different ConsensusEngine above an
# activation height. No serialised structure changes, no header field changes,
# no reindex, and history stays valid because each block is validated by the
# engine that was active at ITS height.
#
# That property was paid for on day one: the block seal lives outside the header
# (DECISIONS.md D2) and ferrum-consensus is forbidden from depending on chain or
# storage (enforced by scripts/check-invariants.sh). This script is where that
# investment gets collected.
set -uo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
require_binaries

LEAD="${FERRUM_FORK_LEAD:-10}"      # activate this many blocks from now

node_running 1 || die "devnet is not running — start it with: bash devnet/up.sh"

current="$(node_height 1)"
[ -n "$current" ] || die "node 1 is not answering RPC"
ACTIVATION=$((current + LEAD))

echo "$(c_bold 'PoW -> BFT fork rehearsal')"
echo "  current height:    $current"
echo "  activation height: $ACTIVATION"
echo "  validators:        $NODES (n=$NODES, f=$(( (NODES - 1) / 3 )), quorum=$(( 2 * ((NODES - 1) / 3) + 1 )))"
echo

[ "$NODES" -ge 4 ] || die "BFT needs at least 4 validators; set FERRUM_DEVNET_NODES=4"

# Every node needs the same activation height and the same validator set, or
# they are on different chains above the fork. That is the intended failure mode.
echo "generating validator keys…"
VALIDATORS=()
for i in $(seq 1 "$NODES"); do
    dir="$(node_dir "$i")"
    keyfile="$dir/validator.key"
    if [ ! -f "$keyfile" ]; then
        "$CHAINCLI" --datadir "$dir" wallet new --output "$keyfile" >/dev/null 2>&1 \
            || die "could not generate a validator key for node $i"
    fi
    pk="$("$CHAINCLI" --datadir "$dir" wallet dump-pubkey --key "$keyfile" 2>/dev/null | tail -1)"
    [ -n "$pk" ] || die "could not read node $i validator public key"
    VALIDATORS+=("$pk")
    echo "  node $i: ${pk:0:20}…"
done

VLIST=$(printf '"%s",' "${VALIDATORS[@]}"); VLIST="[${VLIST%,}]"

echo
echo "writing fork configuration…"
for i in $(seq 1 "$NODES"); do
    cat > "$(node_dir "$i")/fork.toml" <<EOF
# Generated by devnet/fork.sh. Every node must carry an identical copy:
# a node with a different activation height or validator set is, above the fork,
# simply on a different chain.
bft_activation_height = $ACTIVATION
bft_validators = $VLIST
EOF
done

echo "restarting nodes with the fork scheduled…"
for i in $(seq 1 "$NODES"); do stop_node "$i"; done
for i in $(seq 1 "$NODES"); do
    dir="$(node_dir "$i")"
    args=(
        --network devnet --datadir "$dir"
        --rpc-listen "127.0.0.1:$(rpc_port "$i")"
        --p2p-listen "/ip4/127.0.0.1/tcp/$(p2p_port "$i")"
        --explorer-listen "127.0.0.1:$(explorer_port "$i")"
        --index --mine
        --consensus-config "$dir/fork.toml"
        --validator-key "$dir/validator.key"
    )
    for j in $(seq 1 "$NODES"); do [ "$j" != "$i" ] && args+=(--peer "$(peer_addr "$j")"); done
    RUST_LOG="${RUST_LOG:-ferrum_node=info,ferrum_consensus=debug}" \
        "$CHAIND" "${args[@]}" >"$(log_file "$i")" 2>&1 &
    echo $! > "$(pid_file "$i")"
done

printf 'waiting for RPC'
for i in $(seq 1 "$NODES"); do wait_for_rpc "$i" 60 >/dev/null && printf '.' || printf 'x'; done
echo; echo

echo "waiting for the chain to cross height $ACTIVATION…"
waited=0
while [ "$waited" -lt 600 ]; do
    h="$(node_height 1)"
    if [ -n "$h" ] && [ "$h" -ge "$((ACTIVATION + 3))" ]; then break; fi
    printf '\r  height %s / %s ' "${h:-?}" "$ACTIVATION"
    sleep 5; waited=$((waited + 5))
done
echo; echo

engine="$(json_field "$(rpc 1 getblockchaininfo)" engine)"
finalized="$(json_field "$(rpc 1 getblockchaininfo)" finalized_height)"

if [ "$engine" = "bft" ]; then
    echo "$(c_green 'FORK ACTIVATED') — engine is now $engine, finalized height $finalized"
else
    echo "$(c_red 'fork did not activate') — engine is still ${engine:-unknown}"
    exit 1
fi

if tip="$(wait_for_convergence 120 $(seq 1 "$NODES" | tr '\n' ' '))"; then
    echo "$(c_green 'all nodes agree') on ${tip:0:18} across the fork boundary"
else
    echo "$(c_red 'nodes diverged across the fork') — that is a consensus bug"; exit 1
fi

echo
echo "$(c_bold 'Now prove that halting is the correct failure mode:')"
echo "  bash devnet/kill.sh 4     one validator down of $NODES — the chain keeps going"
echo "  bash devnet/kill.sh 3     two down — the chain HALTS, and that is correct."
echo
echo "$(c_dim 'A BFT chain that kept producing blocks without a quorum would be forking,')"
echo "$(c_dim 'and a fork is strictly worse than a stop: a halt is visible and recoverable,')"
echo "$(c_dim 'a fork silently splits balances.')"
