//! A deterministic pseudo-random number generator for fixture generation.
//!
//! Every fixture in this crate is generated from an explicit seed. `rand`'s
//! `thread_rng` seeds itself from the operating system, so a scenario built
//! with it would produce a different chain on every run: a failure would not
//! reproduce, and the golden state-root file in `golden/` could never be
//! stable. Determinism is the whole point of this crate, so the generator is
//! written out here rather than pulled in.
//!
//! The algorithm is Marsaglia's `xorshift64*`: three shift-xor steps followed
//! by one odd multiplication. It is not cryptographic and does not need to be
//! — nothing here defends a secret. What it must be is *specified*, so that
//! the same seed gives the same bytes on every platform, in debug and in
//! release. All arithmetic is `wrapping_*` on `u64`, which is exact and
//! architecture-independent.

/// A seeded `xorshift64*` generator.
///
/// ```
/// use ferrum_sim::XorShift64;
///
/// let mut a = XorShift64::new(7);
/// let mut b = XorShift64::new(7);
/// assert_eq!(a.next_u64(), b.next_u64());
/// ```
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct XorShift64 {
    state: u64,
}

impl XorShift64 {
    /// The multiplier and the substitute seed for zero.
    ///
    /// `xorshift64` has a fixed point at zero — a zero state produces nothing
    /// but zeroes forever — so a caller that passes `0` gets this constant
    /// instead of a dead generator.
    pub const DEFAULT_SEED: u64 = 0x2545_f491_4f6c_dd1d;

    /// The seed every scenario uses unless it says otherwise.
    ///
    /// One shared default keeps unrelated scenarios from accidentally
    /// depending on each other's stream position.
    pub const SCENARIO_SEED: u64 = 0xfe22_0b10_c4a5_1701;

    /// A generator seeded with `seed`.
    #[must_use]
    pub const fn new(seed: u64) -> Self {
        XorShift64 { state: if seed == 0 { Self::DEFAULT_SEED } else { seed } }
    }

    /// The generator's current internal state.
    ///
    /// Exposed so a test can record where a fixture run started and replay it.
    #[must_use]
    pub const fn state(&self) -> u64 {
        self.state
    }

    /// The next 64 bits.
    pub fn next_u64(&mut self) -> u64 {
        let mut x = self.state;
        x ^= x >> 12;
        x ^= x << 25;
        x ^= x >> 27;
        self.state = x;
        x.wrapping_mul(Self::DEFAULT_SEED)
    }

    /// The next 32 bits, taken from the high half where the mixing is best.
    pub fn next_u32(&mut self) -> u32 {
        // The low bits of an LCG-style output are the weakest; taking the top
        // half is the standard fix and costs nothing.
        u32::try_from(self.next_u64() >> 32).unwrap_or(0)
    }

    /// A value in `0..n`, without modulo bias.
    ///
    /// Lemire's multiply-shift: scale a 64-bit draw into the range with a
    /// 128-bit product and keep the high half. `n == 0` yields `0`.
    pub fn below(&mut self, n: u64) -> u64 {
        if n == 0 {
            return 0;
        }
        let draw = u128::from(self.next_u64());
        let scaled = draw.wrapping_mul(u128::from(n)) >> 64;
        u64::try_from(scaled).unwrap_or(0)
    }

    /// A value in `low..=high`. Returns `low` when the range is inverted.
    pub fn range(&mut self, low: u64, high: u64) -> u64 {
        if high <= low {
            return low;
        }
        let span = high.saturating_sub(low).saturating_add(1);
        low.saturating_add(self.below(span))
    }

    /// A `usize` in `0..n`.
    pub fn below_usize(&mut self, n: usize) -> usize {
        usize::try_from(self.below(n as u64)).unwrap_or(0)
    }

    /// `true` with probability `numerator / denominator`.
    pub fn chance(&mut self, numerator: u64, denominator: u64) -> bool {
        if denominator == 0 {
            return false;
        }
        self.below(denominator) < numerator
    }

    /// Fill `out` with generated bytes.
    pub fn fill_bytes(&mut self, out: &mut [u8]) {
        for chunk in out.chunks_mut(8) {
            let word = self.next_u64().to_le_bytes();
            let n = chunk.len().min(word.len());
            chunk[..n].copy_from_slice(&word[..n]);
        }
    }

    /// A fresh 32-byte array.
    pub fn bytes32(&mut self) -> [u8; 32] {
        let mut out = [0u8; 32];
        self.fill_bytes(&mut out);
        out
    }

    /// Pick an index into a slice of length `len`, or `None` when empty.
    pub fn index(&mut self, len: usize) -> Option<usize> {
        if len == 0 { None } else { Some(self.below_usize(len)) }
    }
}

impl Default for XorShift64 {
    fn default() -> Self {
        Self::new(Self::DEFAULT_SEED)
    }
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeSet;

    use super::*;

    #[test]
    fn the_same_seed_gives_the_same_stream() {
        let mut a = XorShift64::new(12345);
        let mut b = XorShift64::new(12345);
        for _ in 0..1000 {
            assert_eq!(a.next_u64(), b.next_u64());
        }
    }

    #[test]
    fn different_seeds_diverge_immediately() {
        let mut a = XorShift64::new(1);
        let mut b = XorShift64::new(2);
        assert_ne!(a.next_u64(), b.next_u64());
    }

    #[test]
    fn a_zero_seed_is_replaced_rather_than_producing_zeroes() {
        let mut zero = XorShift64::new(0);
        assert_eq!(zero.state(), XorShift64::DEFAULT_SEED);
        assert_ne!(zero.next_u64(), 0);
    }

    #[test]
    fn below_stays_inside_the_range() {
        let mut rng = XorShift64::new(99);
        for _ in 0..10_000 {
            assert!(rng.below(7) < 7);
        }
        assert_eq!(rng.below(0), 0);
        assert_eq!(rng.below(1), 0);
    }

    #[test]
    fn range_is_inclusive_at_both_ends_and_never_escapes() {
        let mut rng = XorShift64::new(4);
        let mut seen = BTreeSet::new();
        for _ in 0..10_000 {
            let v = rng.range(10, 13);
            assert!((10..=13).contains(&v));
            seen.insert(v);
        }
        assert_eq!(seen, BTreeSet::from([10, 11, 12, 13]));
        assert_eq!(rng.range(5, 5), 5);
        assert_eq!(rng.range(9, 3), 9);
    }

    #[test]
    fn the_stream_does_not_repeat_over_a_short_window() {
        let mut rng = XorShift64::new(XorShift64::SCENARIO_SEED);
        let seen: BTreeSet<u64> = (0..20_000).map(|_| rng.next_u64()).collect();
        assert_eq!(seen.len(), 20_000, "a short cycle would ruin fixture coverage");
    }

    #[test]
    fn fill_bytes_handles_a_partial_final_chunk() {
        let mut rng = XorShift64::new(5);
        let mut buf = [0u8; 13];
        rng.fill_bytes(&mut buf);
        assert!(buf.iter().any(|b| *b != 0));
    }

    #[test]
    fn index_is_none_only_for_an_empty_slice() {
        let mut rng = XorShift64::new(6);
        assert_eq!(rng.index(0), None);
        for _ in 0..100 {
            let i = rng.index(3).expect("non-empty");
            assert!(i < 3);
        }
    }

    #[test]
    fn chance_is_bounded_by_its_extremes() {
        let mut rng = XorShift64::new(8);
        for _ in 0..200 {
            assert!(!rng.chance(0, 10));
            assert!(rng.chance(10, 10));
            assert!(!rng.chance(1, 0));
        }
    }
}
